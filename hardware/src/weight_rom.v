// ============================================================
// weight_rom.v — 가중치 ROM (48 × INT8)
// ============================================================
// neuron_idx에 따라 해당 뉴런의 가중치 벡터를 출력합니다.
//
// 은닉 뉴런 (idx 0~3): 10개 가중치 → weights[79:0]
// 출력 뉴런 (idx 4~5): 4개 가중치  → weights[31:0] (상위 48비트 = 0)
//
// 가중치는 학습 후 INT8 양자화된 값으로 교체합니다.
// 현재는 테스트용 임의값이 들어 있습니다.
//
// 순수 조합논리 (ROM). 클럭 불필요.
// ============================================================

module weight_rom #(
    parameter W_WIDTH = 8
)(
    input  wire [2:0]            neuron_idx,  // 0~5
    output reg  [10*W_WIDTH-1:0] weights      // 가중치 벡터 (flat bus)
);

    // -------------------------------------------------------
    // 가중치 테이블
    // -------------------------------------------------------
    // ★ 학습 완료 후 이 값들을 양자화된 가중치로 교체할 것
    //
    // 패킹 순서: {w9, w8, w7, w6, w5, w4, w3, w2, w1, w0}
    // 즉 weights[7:0] = w0, weights[15:8] = w1, ...

    always @(*) begin
        case (neuron_idx)
            // --- 은닉층 (W1): 각 10개 가중치 ---
            3'd0: // H0 (β=0.70, 충격 감지)
                weights = {8'sd5,  8'sd5,  8'sd5,  8'sd5,  8'sd5,
                           8'sd5,  8'sd5,  8'sd10, 8'sd80, 8'sd100};

            3'd1: // H1 (β=0.80, 중주파 진동)
                weights = {8'sd30, 8'sd30, 8'sd30, 8'sd30, 8'sd30,
                           8'sd30, 8'sd30, 8'sd30, 8'sd30, 8'sd30};

            3'd2: // H2 (β=0.90, 베어링 마모)
                weights = {8'sd15, 8'sd15, 8'sd15, 8'sd15, 8'sd15,
                           8'sd15, 8'sd15, 8'sd15, 8'sd15, 8'sd15};

            3'd3: // H3 (β=0.95, 장기 추세)
                weights = {8'sd10, 8'sd10, 8'sd10, 8'sd10, 8'sd10,
                           8'sd10, 8'sd10, 8'sd10, 8'sd10, 8'sd10};

            // --- 출력층 (W2): 각 4개 가중치, 상위 6개는 0 ---
            3'd4: // Out0 (정상)
                weights = {8'sd0, 8'sd0, 8'sd0, 8'sd0, 8'sd0, 8'sd0,
                           8'sd20, 8'sd30, 8'sd100, 8'sd120};

            3'd5: // Out1 (이상)
                weights = {8'sd0, 8'sd0, 8'sd0, 8'sd0, 8'sd0, 8'sd0,
                           8'sd120, 8'sd100, 8'sd30, 8'sd20};

            default:
                weights = 80'd0;
        endcase
    end

endmodule
